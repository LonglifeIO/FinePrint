// Machine-specific settings live in the gitignored local.properties, never in the repo:
//   fineprint.bundleUrl=http://<host>:8080/   (debug bundle server; default: the emulator's host loopback)
//   fineprint.cleartextHost=<host>            (extra host allowed over plain HTTP in debug, e.g. a Tailscale name)
val localProps = Properties().apply {
    rootProject.file("local.properties").takeIf { it.exists() }?.inputStream()?.use { load(it) }
}
val debugBundleUrl = localProps.getProperty("fineprint.bundleUrl") ?: "http://10.0.2.2:8080/"
val debugCleartextHost = localProps.getProperty("fineprint.cleartextHost").orEmpty()

